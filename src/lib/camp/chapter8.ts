// 统一抽题工具：口试 15 选 7，情景 10 选 5，判断 5 题全做
export function pickFinalQuestions(seed?: number): {
  oral: FinalOralQuestion[];
  scenario: FinalOralQuestion[];
  judge: FinalJudgeQuestion[];
} {
  const random = seed
    ? mulberry32(seed)
    : () => Math.random();
  const oral = shuffle(oralQuestions, random).slice(0, FINAL_EXAM_INFO.oralCount);
  const scenario = shuffle(scenarioQuestions, random).slice(0, FINAL_EXAM_INFO.scenarioCount);
  return { oral, scenario, judge: [...judgeQuestions] };
}

function shuffle<T>(arr: T[], rand: () => number): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function mulberry32(a: number): () => number {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

